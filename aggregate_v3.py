"""Aggregate runs_v3/*.json -> summary_v3.json + RESULTS_v3.md (no hand-typed numbers)."""
import glob, json, os
import numpy as np, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ccl_sim as C


def holdings_from_sql(hs):
    """rebuild executable holdings from the stored SQL: every condition (incl. disc bounds) becomes a literal"""
    out = []
    for h in hs:
        conds, verdict = h["sql"].split("  => ")
        kind = "loosen" if verdict == "APPROVE" else "tighten"
        out.append(dict(id=h["id"], kind=kind, lits=conds.split(" AND "), cap=1e9 if kind == "loosen" else -1e9))
    return out


def recompute_recovery(r):
    C.set_world(r["world"])
    fresh = C.make_firm(np.random.default_rng(r["seed"] + 1000), 60000, r["bad_renew"], month=C.TEST_START - 1)
    return C.recovery(holdings_from_sql(r["snapshots"]["36"]["holdings"]), fresh, None)


def fidelity(r):
    """share of each hidden rule's cases (rule applies, not overridden) that CCL's month-36 holdings decide like the rule"""
    C.set_world(r["world"])
    fresh = C.make_firm(np.random.default_rng(r["seed"] + 1000), 60000, r["bad_renew"], month=C.TEST_START - 1)
    hs = holdings_from_sql(r["snapshots"]["36"]["holdings"]); pred, _ = C.apply(hs, fresh, None)
    t_over = C.TIGHT[1](fresh).values & (fresh.disc.values > C.TIGHT[2]); out = {}
    for name, fn, c in C.LOOSEN:
        cv = C.cap_of(c, fresh); a = fn(fresh).values & ~fresh.statute.values & (fresh.disc.values <= cv) & ~t_over
        out[name] = float(pred[a].mean()) if a.sum() else float("nan")
    a = C.TIGHT[1](fresh).values & (fresh.disc.values > C.TIGHT[2]) & fresh.statute.values
    out[C.TIGHT[0]] = float((~pred[a]).mean())
    return out

HERE = os.path.dirname(os.path.abspath(__file__))
runs = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(HERE, "runs_v3", "*.json")))]
mean = lambda xs: float(np.mean(xs)) if len(xs) else float("nan")
METHODS = [("statute", "policy"), ("gbm_monthly", "GBM"), ("gbm_outcome", "GBM+relabel"), ("gbm_uplift", "GBM+renewal veto"),
           ("ccl", "CCL"), ("ccl_goodlaw", "CCL+bad-law")]
S = {"n_runs": len(runs), "worlds": {}}
for world in ["easy", "hard"]:
    W = S["worlds"][world] = {"miners": {}}
    for miner in ["schema", "beam", "tree", "covering"]:
        rs = [r for r in runs if r.get("world") == world and r["miner"] == miner and r["bad_renew"] == 0.35]
        if not rs: continue
        acc = {k: {v: mean([r["accuracy"][k][v] for r in rs]) for v in ["vs_actual", "vs_good"]} for k, _ in METHODS}
        rec = [recompute_recovery(r) for r in rs]; rules = list(rec[0])  # recomputed from stored SQL with the current metric
        W["miners"][miner] = dict(seeds=sorted(r["seed"] for r in rs), accuracy=acc,
                                  exact=mean([sum(x[n].get("exact", False) for n in rules) for x in rec]), n_rules=len(rules),
                                  per_rule={n: dict(exact=mean([x[n].get("exact", False) for x in rec]), union=mean([x[n].get("union_coverage", 0) for x in rec]),
                                                    example=rec[0][n].get("holding")) for n in rules},
                                  holdings=mean([len(r["snapshots"]["36"]["holdings"]) for r in rs]))
        fid = [fidelity(r) for r in rs]
        W["miners"][miner]["fidelity"] = {n: mean([f[n] for f in fid]) for n in fid[0]}
    sw = {}
    for r in [r for r in runs if r.get("world") == world and r["miner"] == "schema"]:
        sw.setdefault(str(r["bad_renew"]), []).append(r)
    W["sweep"] = {b: dict(n=len(rs), flagged=mean([mean([l["rogue_flagged"] for l in r["log"]]) for r in rs]),
                          **{k + "_vs_good": mean([r["accuracy"][k]["vs_good"] for r in rs]) for k in ["ccl", "ccl_goodlaw", "gbm_monthly", "gbm_uplift"]})
                  for b, rs in sorted(sw.items())}
json.dump(S, open(os.path.join(HERE, "summary_v3.json"), "w"), indent=1)

L = ["# CCL v3: hard world + strongest baseline (auto-generated by aggregate_v3.py from runs_v3/*.json)", "",
     "easy world = v2 rules (conjunction + cap). hard world = hidden rules OUTSIDE that shape: OR-rule, term-scaled cap interaction,",
     "odd threshold (340k), a field v2 never used (customer tenure >= 11y), a negation (outside France); same rogue rule + Germany rule.",
     "Miners: schema = v2 hand-picked literals (cannot see tenure, negations, 340); beam = generic literals built from every column.",
     "GBM+renewal veto = strongest black box: same outcome info and same 0.20 threshold as the bad-law filter, no rules.", ""]
for world, W in S["worlds"].items():
    L += [f"## {world} world (bad_renew = 0.35, mean over seeds)", "", "| miner | target | " + " | ".join(n for _, n in METHODS) + " | rules exact | mean fidelity | holdings |",
          "|---|---|" + "---|" * len(METHODS) + "---|---|---|"]
    for miner, m in W["miners"].items():
        for v in ["vs_actual", "vs_good"]:
            L.append(f"| {miner} | {v} | " + " | ".join(f"{m['accuracy'][k][v]:.3f}" for k, _ in METHODS) +
                     (f" | {m['exact']:.1f}/{m['n_rules']} | {mean(list(m['fidelity'].values())):.2f} | {m['holdings']:.1f} |" if v == "vs_actual" else " | | | |"))
    if "beam" in W["miners"]:
        L += ["", f"{world} world, beam miner, per rule (exact = cov>=.6 & purity>=.8; union = coverage by all pure holdings):", "",
              "| rule | exact | union | fidelity (share of the rule's cases decided like the rule) | example holding (first seed) |", "|---|---|---|---|---|"]
        for n, p in W["miners"]["beam"]["per_rule"].items(): L.append(f"| {n} | {p['exact']:.2f} | {p['union']:.2f} | {W['miners']['beam']['fidelity'][n]:.2f} | `{p['example']}` |")
    if W["sweep"]:
        L += ["", f"{world} world, schema miner, outcome-effect sweep (vs_good):", "", "| rogue renewal rate | months flagged | CCL | CCL+bad-law | GBM | GBM+renewal veto |", "|---|---|---|---|---|---|"]
        for b, s in W["sweep"].items():
            L.append(f"| {b} | {s['flagged']:.0%} | {s['ccl_vs_good']:.3f} | {s['ccl_goodlaw_vs_good']:.3f} | {s['gbm_monthly_vs_good']:.3f} | {s['gbm_uplift_vs_good']:.3f} |")
    L.append("")
open(os.path.join(HERE, "RESULTS_v3.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
