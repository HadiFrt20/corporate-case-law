"""Aggregate runs/*.json into summary.json + RESULTS.md (no hand-typed numbers)."""
import glob, json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
runs = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(HERE, "runs", "*.json")))]
mean = lambda xs: float(np.mean(xs)) if xs else float("nan")
S = {"n_runs": len(runs), "miners": {}, "sweep": {}, "decay": {}}

for miner in ["schema", "tree", "covering"]:
    rs = [r for r in runs if r["miner"] == miner and r["bad_renew"] == 0.35]
    if not rs: continue
    acc = {k: {v: mean([r["accuracy"][k][v] for r in rs]) for v in ["vs_actual", "vs_good"]} for k in rs[0]["accuracy"]}
    gap = lambda k, v: (acc[k][v] - acc["statute"][v]) / (acc["gbm_monthly"][v] - acc["statute"][v])
    rec36 = [r["snapshots"]["36"]["recovery"] for r in rs]
    rules = list(rec36[0])
    S["miners"][miner] = dict(
        seeds=[r["seed"] for r in rs], accuracy=acc,
        gap_closed_vs_actual={k: round(gap(k, "vs_actual"), 3) for k in ["ccl", "ccl_goodlaw"]},
        exact_recovered=mean([sum(rc[n].get("exact", False) for n in rules) for rc in rec36]), n_rules=len(rules),
        per_rule={n: dict(exact=mean([rc[n].get("exact", False) for rc in rec36]), union_coverage=mean([rc[n].get("union_coverage", 0) for rc in rec36]),
                          example=rec36[0][n].get("holding")) for n in rules},
        n_holdings=mean([len(r["snapshots"]["36"]["holdings"]) for r in rs]))
    S["decay"][miner] = {m: mean([next(l["r1_holding_admitted"] for l in r["log"] if l["month"] == m) for r in rs]) for m in range(36, 48)}

for b in sorted({r["bad_renew"] for r in runs}):
    rs = [r for r in runs if r["miner"] == "schema" and r["bad_renew"] == b]
    first = [next((l["month"] for l in r["log"] if l["rogue_flagged"]), None) for r in rs]
    S["sweep"][str(b)] = dict(seeds=len(rs), flagged_month_share=mean([mean([l["rogue_flagged"] for l in r["log"]]) for r in rs]),
                              first_flag_month=first, ccl_goodlaw_vs_good=mean([r["accuracy"]["ccl_goodlaw"]["vs_good"] for r in rs]),
                              ccl_vs_good=mean([r["accuracy"]["ccl"]["vs_good"] for r in rs]), gbm_vs_good=mean([r["accuracy"]["gbm_monthly"]["vs_good"] for r in rs]), gbm_outcome_vs_good=mean([r["accuracy"]["gbm_outcome"]["vs_good"] for r in rs]),
                              pending_mean=mean([mean([l["pending"] for l in r["log"]]) for r in rs]))
ex = next((r for r in runs if r["miner"] == "schema" and r["bad_renew"] == 0.35 and r["seed"] == 7), None)
S["example_holdings_seed7_m36"] = ex["snapshots"]["36"]["holdings"] if ex else []
json.dump(S, open(os.path.join(HERE, "summary.json"), "w"), indent=1)

L = ["# CCL falsification v2 (auto-generated by aggregate.py from runs/*.json)", "",
     "Synthetic firm: 120K discount decisions over 48 months, written policy max 15%, 7 planted tacit rules, 4% noise.",
     "Online test months 36-47, trailing 12-month window. Renewal outcomes visible only at month + 12*term.",
     "`vs_actual` = agreement with logged decisions (incl. rogue approvals + noise). `vs_good` = agreement with the policy-consistent, noiseless decision.", "",
     "## Accuracy (bad_renew = 0.35, mean over seeds)", "",
     "| miner | metric | statute | GBM monthly | GBM + outcomes | CCL (all holdings) | CCL + bad-law filter | gap closed vs actual (CCL / filtered) |", "|---|---|---|---|---|---|---|---|"]
for miner, s in S["miners"].items():
    a = s["accuracy"]
    for v in ["vs_actual", "vs_good"]:
        gc = f"{s['gap_closed_vs_actual']['ccl']:.0%} / {s['gap_closed_vs_actual']['ccl_goodlaw']:.0%}" if v == "vs_actual" else ""
        L.append(f"| {miner} | {v} | {a['statute'][v]:.3f} | {a['gbm_monthly'][v]:.3f} | {a['gbm_outcome'][v]:.3f} | {a['ccl'][v]:.3f} | {a['ccl_goodlaw'][v]:.3f} | {gc} |")
L += ["", "## Rule recovery at month 36 (fresh 60K sample, binding-cap effect masks)", "", "| miner | exact (best single holding cov>=.6, purity>=.8) | holdings |", "|---|---|---|"]
for miner, s in S["miners"].items(): L.append(f"| {miner} | {s['exact_recovered']:.1f} / {s['n_rules']} | {s['n_holdings']:.1f} |")
if "schema" in S["miners"]:
    L += ["", "Schema miner, per rule:", "", "| rule | exact (share of seeds) | union coverage | example holding (seed 7) |", "|---|---|---|---|"]
    for n, p in S["miners"]["schema"]["per_rule"].items(): L.append(f"| {n} | {p['exact']:.2f} | {p['union_coverage']:.2f} | `{p['example']}` |")
L += ["", "## Bad-law detection vs outcome effect size (schema miner)", "", "| renewal rate of rogue approvals (others 0.85) | months flagged | first flag month per seed | holdings pending outcome (mean) | CCL+filter vs_good | CCL vs_good | GBM vs_good | GBM+outcomes vs_good |", "|---|---|---|---|---|---|---|---|"]
for b, s in S["sweep"].items():
    L.append(f"| {b} | {s['flagged_month_share']:.0%} | {s['first_flag_month']} | {s['pending_mean']:.1f} | {s['ccl_goodlaw_vs_good']:.3f} | {s['ccl_vs_good']:.3f} | {s['gbm_vs_good']:.3f} | {s['gbm_outcome_vs_good']:.3f} |")
L += ["", "## Decay: is a holding for R1 (retired at month 40) admitted? share of seeds", "", "| miner | " + " | ".join(str(m) for m in range(36, 48)) + " |", "|---|" + "---|" * 12]
for miner, d in S["decay"].items(): L.append(f"| {miner} | " + " | ".join(f"{d[m] if isinstance(d, dict) and m in d else d[str(m)]:.2f}" for m in range(36, 48)) + " |")
open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
